/** 最近使用表情的 localStorage 键与容量上限 */
export const EMOJI_RECENT_KEY = 'md-emoji-recent'
export const EMOJI_RECENT_MAX = 32

/** 读取最近使用的表情（损坏或缺失时返回空数组） */
export function loadRecentEmojis(): string[] {
  try {
    const raw = localStorage.getItem(EMOJI_RECENT_KEY)
    const arr = raw ? JSON.parse(raw) : []
    return Array.isArray(arr) ? arr.filter((e) => typeof e === 'string') : []
  } catch {
    return []
  }
}

/** 记录最近使用（去重置顶，超限截断），返回新列表 */
export function pushRecentEmoji(emoji: string): string[] {
  const list = [emoji, ...loadRecentEmojis().filter((e) => e !== emoji)].slice(0, EMOJI_RECENT_MAX)
  try {
    localStorage.setItem(EMOJI_RECENT_KEY, JSON.stringify(list))
  } catch {
    /* 存储失败不影响插入 */
  }
  return list
}
